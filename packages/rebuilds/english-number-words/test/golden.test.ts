import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { toWords, toOrdinalWords, toTuple } from "../src/index.js";

type Row = { kind: "words"; n: string; and: string; noAnd: string } | { kind: "ordinal"; n: string; ord: string } | { kind: "tuple"; n: string; tuple: string };
const rows: Row[] = readFileSync(new URL("../fixtures/humanizer-2.14.1-golden.jsonl", import.meta.url), "utf8").trim().split("\n").map((l) => JSON.parse(l));

describe("golden parity with the original Humanizer 2.14.1 (generated by tools/humanizer-oracle)", () => {
  it("has a broad golden set", () => expect(rows.length).toBeGreaterThan(4000));
  it("ToWords() with and without 'and' matches every golden row", () => {
    const bad: string[] = [];
    for (const r of rows) if (r.kind === "words") {
      if (toWords(BigInt(r.n)) !== r.and) bad.push(`${r.n}: ${toWords(BigInt(r.n))} != ${r.and}`);
      if (toWords(BigInt(r.n), { addAnd: false }) !== r.noAnd) bad.push(`${r.n} (no and)`);
    }
    expect(bad).toEqual([]);
  });
  it("ToOrdinalWords() matches every golden row", () => {
    const bad = rows.filter((r): r is Extract<Row, { kind: "ordinal" }> => r.kind === "ordinal").filter((r) => toOrdinalWords(BigInt(r.n)) !== r.ord);
    expect(bad).toEqual([]);
  });
  it("ToTuple() matches every golden row", () => {
    const bad = rows.filter((r): r is Extract<Row, { kind: "tuple" }> => r.kind === "tuple").filter((r) => toTuple(BigInt(r.n)) !== r.tuple);
    expect(bad).toEqual([]);
  });
});

describe("documented quirks of the original, preserved", () => {
  it("addAnd=false only drops the final 'and'", () => expect(toWords(101101, { addAnd: false })).toBe("one hundred and one thousand one hundred one"));
  it("negative ordinals come out cardinal", () => expect(toOrdinalWords(-5)).toBe("minus five"));
  it("leading 'one' is dropped from ordinals", () => expect(toOrdinalWords(100)).toBe("hundredth"));
  it("rejects non-integers and out-of-range input", () => {
    expect(() => toWords(1.5)).toThrow(RangeError);
    expect(() => toOrdinalWords(2 ** 31)).toThrow(/Int32/);
    expect(() => toWords(-(2n ** 63n))).toThrow(/MinValue/);
  });
});
